// scripts/build-name-font.mjs
// Regenerates src/geometry/name-font-data.ts: the outlines of the engraved names, a subset of
// Overpass Bold (SIL OFL 1.1, licenses/overpass-OFL.txt). Run by hand, not by the build:
//   npm i --no-save opentype.js@1.3.4
//   node scripts/build-name-font.mjs path/to/Overpass-Bold.ttf > src/geometry/name-font-data.ts
// Overpass 4.0 desktop fonts: https://github.com/RedHatOfficial/Overpass (fonts/ttf/Overpass-Bold.ttf).
import { createRequire } from "node:module";
import { readFileSync } from "node:fs";

const require = createRequire(import.meta.url);
const opentype = require("opentype.js");

const file = process.argv[2];
if (file === undefined) {
  console.error("usage: node scripts/build-name-font.mjs <Overpass-Bold.ttf>");
  process.exit(1);
}
const buf = readFileSync(file);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const CHARS = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789- ";
const TOL = 4; // flattening tolerance, font units (2000 per em: 0.02 mm on an 8 mm capital)

/** A quadratic or cubic Bezier flattened by uniform steps (enough segments for TOL). */
function curve(pts, out) {
  const len = pts.reduce(
    (s, p, i) => (i === 0 ? 0 : s + Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1])),
    0,
  );
  const n = Math.max(2, Math.ceil(Math.sqrt(len / (8 * TOL)) * 2));
  for (let i = 1; i <= n; i += 1) {
    const t = i / n;
    let q = pts;
    while (q.length > 1) {
      q = q
        .slice(1)
        .map((p, k) => [q[k][0] + (p[0] - q[k][0]) * t, q[k][1] + (p[1] - q[k][1]) * t]);
    }
    out.push(q[0]);
  }
}

function contoursOf(ch) {
  const path = font.charToGlyph(ch).getPath(0, 0, font.unitsPerEm);
  const contours = [];
  let cur = [];
  let at = [0, 0];
  for (const c of path.commands) {
    if (c.type === "M") {
      if (cur.length > 2) contours.push(cur);
      cur = [[c.x, -c.y]];
      at = [c.x, -c.y];
    } else if (c.type === "L") {
      cur.push([c.x, -c.y]);
      at = [c.x, -c.y];
    } else if (c.type === "Q") {
      curve([at, [c.x1, -c.y1], [c.x, -c.y]], cur);
      at = [c.x, -c.y];
    } else if (c.type === "C") {
      curve([at, [c.x1, -c.y1], [c.x2, -c.y2], [c.x, -c.y]], cur);
      at = [c.x, -c.y];
    } else if (c.type === "Z") {
      if (cur.length > 2) contours.push(cur);
      cur = [];
    }
  }
  if (cur.length > 2) contours.push(cur);
  // integer font units, repeated points dropped
  return contours.map((contour) => {
    const pts = contour.map(([x, y]) => [Math.round(x), Math.round(y)]);
    return pts.filter((p, i) => i === 0 || p[0] !== pts[i - 1][0] || p[1] !== pts[i - 1][1]);
  });
}

const glyphs = {};
for (const ch of CHARS) {
  const g = font.charToGlyph(ch);
  glyphs[ch] = {
    adv: g.advanceWidth,
    c: contoursOf(ch)
      .map((c) => c.map((p) => p.join(",")).join(" "))
      .join("|"),
  };
}
const kern = {};
for (const a of CHARS) {
  for (const b of CHARS) {
    const k = font.getKerningValue(font.charToGlyph(a), font.charToGlyph(b));
    // under 15 units (0.09 mm on an 8 mm capital) is noise to a 0.4 mm nozzle
    if (Math.abs(k) >= 15) kern[a + b] = k;
  }
}
const os2 = font.tables.os2;
console.log(`// src/geometry/name-font-data.ts
// GENERATED by scripts/build-name-font.mjs. Do not edit by hand.
// A subset of Overpass Bold ${font.names.version?.en ?? ""} (c) The Overpass Project Authors, SIL Open Font
// License 1.1 (licenses/overpass-OFL.txt): A-Z, 0-9, hyphen and space, as flattened outlines.
// Units are font units; y grows upward, the baseline is 0.

export const FONT_CAP_HEIGHT = ${os2.sCapHeight};

/** Per character: its advance and its contours ("x,y x,y …", contours joined by "|"). */
export const FONT_GLYPHS: Readonly<Record<string, { adv: number; c: string }>> = ${JSON.stringify(glyphs)};

/** Pair adjustments (two characters, then font units added to the first's advance). */
export const FONT_KERNING: Readonly<Record<string, number>> = ${JSON.stringify(kern)};`);
